const SCHEMA_VERSION = '2026-06-27.data-factory-node-bootstrap.v1'
const DEFAULT_STAGE_BINDINGS = [
  'ingestion-queue',
  'environmental-extractors',
  'semantic-materialization',
  'viewer-artifacts',
]

const CONNECTION_MODE_BY_PROVIDER = new Map([
  ['same-server-sidecar', 'local'],
  ['server-to-server-pull', 'pull'],
  ['server-to-server-push', 'push'],
  ['offline-bundle', 'offline'],
  ['hpc-batch', 'batch'],
  ['cloud-batch', 'cloud'],
  ['manual-import', 'manual'],
])

function argValues(name, argv = process.argv.slice(2)) {
  const prefix = `--${name}=`
  return argv
    .filter((entry) => entry.startsWith(prefix))
    .map((entry) => entry.slice(prefix.length))
    .filter(Boolean)
}

function argValue(name, argv = process.argv.slice(2)) {
  return argValues(name, argv)[0] ?? ''
}

function booleanArg(name, argv = process.argv.slice(2)) {
  return argv.includes(`--${name}`) || argv.includes(`--${name}=true`)
}

function normalizeKey(value, fallback = '') {
  const normalized = (String(value ?? '').trim() || fallback)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/^-+|-+$/g, '')
  if (!/^[a-z0-9][a-z0-9._-]{1,128}$/.test(normalized)) {
    throw new Error('DATA_FACTORY_NODE_KEY_INVALID')
  }
  return normalized
}

function requireText(value, errorCode) {
  const normalized = String(value ?? '').trim()
  if (!normalized) throw new Error(errorCode)
  return normalized
}

function enumValue(value, allowed, fallback, errorCode) {
  const normalized = String(value ?? '').trim() || fallback
  if (!allowed.includes(normalized)) throw new Error(errorCode)
  return normalized
}

function splitList(values, fallback = []) {
  const entries = values.flatMap((value) => String(value ?? '').split(','))
    .map((value) => value.trim())
    .filter(Boolean)
  return entries.length ? entries : fallback
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`
}

function writeFile(file, content, mode = null) {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
  if (mode !== null) fs.chmodSync(file, mode)
}

function envLine(key, value) {
  return `${key}=${String(value ?? '').replace(/\n/g, '')}`
}

function buildEnvFile({
  nodeKey,
  providerType,
  connectionMode,
  runtimeKind,
  twinStudioUrl,
  runtimeToken,
  heartbeatUrl,
  projectName,
  imageRef,
  postgisContainer,
  postgisBind,
  smokeCityId,
}) {
  return `${[
    '# Generated by npm run ops:bootstrap-data-factory-node.',
    '# This file may contain a runtime token. Keep it outside git.',
    envLine('DATAFACTORY_NODE_KEY', nodeKey),
    envLine('DATAFACTORY_PROVIDER_TYPE', providerType),
    envLine('DATAFACTORY_CONNECTION_MODE', connectionMode),
    envLine('DATAFACTORY_RUNTIME_KIND', runtimeKind),
    envLine('TWIN_STUDIO_BASE_URL', twinStudioUrl),
    envLine('DATAFACTORY_HEARTBEAT_URL', heartbeatUrl),
    envLine('TWIN_STUDIO_DATA_FACTORY_TOKEN', runtimeToken),
    '',
    envLine('DATAFACTORY_PROJECT_NAME', projectName),
    envLine('DATAFACTORY_IMAGE', imageRef),
    envLine('DATAFACTORY_POSTGIS_CONTAINER', postgisContainer),
    envLine('DATAFACTORY_POSTGIS_BIND', postgisBind),
    '',
    envLine('TWIN_STUDIO_POSTGRES_DB', 'twin_base_studio'),
    envLine('TWIN_STUDIO_POSTGRES_USER', 'twin_base_studio'),
    envLine('TWIN_STUDIO_POSTGRES_PASSWORD', 'change-me-before-running'),
    envLine('TWIN_STUDIO_DATABASE_URL', 'postgresql://twin_base_studio:change-me-before-running@postgis:5432/twin_base_studio'),
    envLine('TWIN_STUDIO_DATABASE_POOL_SIZE', '8'),
    envLine('TWIN_STUDIO_DATABASE_CONNECT_TIMEOUT_MS', '15000'),
    envLine('TWIN_STUDIO_SMOKE_CITY_ID', smokeCityId),
  ].join('\n')}\n`
}

function buildInstallScript({ nodeKey, heartbeatUrl }) {
  return `#!/usr/bin/env bash
set -euo pipefail

ROOT="\${1:-$PWD/twin-base-studio-datafactory-${nodeKey}}"
SCRIPT_DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"

mkdir -p "\${ROOT}"
echo "DATAFACTORY_INSTALL_ROOT=\${ROOT}"

if [[ ! -f "\${ROOT}/.env.datafactory" ]]; then
  cp "\${SCRIPT_DIR}/.env.datafactory.node" "\${ROOT}/.env.datafactory"
  echo "DATAFACTORY_ENV_CREATED=\${ROOT}/.env.datafactory"
else
  echo "DATAFACTORY_ENV_EXISTS=\${ROOT}/.env.datafactory"
fi

cat <<'NOTE'
Next:
1. Extract or rsync the Data Factory bundle into DATAFACTORY_INSTALL_ROOT.
2. Review .env.datafactory and replace change-me-before-running values.
3. Run:
   docker compose --env-file .env.datafactory -f compose.datafactory.yml up -d postgis
   docker compose --env-file .env.datafactory -f compose.datafactory.yml --profile runner build runner
   docker compose --env-file .env.datafactory -f compose.datafactory.yml --profile runner run --rm runner npm run ops:datafactory:doctor -- --require-db
NOTE

if command -v curl >/dev/null 2>&1; then
  set -a
  . "\${ROOT}/.env.datafactory"
  set +a
  if [[ -n "\${TWIN_STUDIO_DATA_FACTORY_TOKEN:-}" ]]; then
    curl -fsS -X POST "${heartbeatUrl}" \\
      -H "Authorization: Bearer \${TWIN_STUDIO_DATA_FACTORY_TOKEN}" \\
      -H "content-type: application/json" \\
      -d '{"status":"online","doctorStatus":"unknown","doctor":{"bootstrap":"installed"},"capabilities":{"bootstrap":"generated-install-script"}}' \\
      >/dev/null && echo "DATAFACTORY_HEARTBEAT_SENT=${nodeKey}" || echo "DATAFACTORY_HEARTBEAT_SKIPPED=${nodeKey}"
  fi
fi
`
}

function buildBootstrapJson({
  node,
  providerType,
  connectionMode,
  runtimeKind,
  runtimeVersion,
  imageRef,
  twinStudioUrl,
  heartbeatUrl,
  stageBindings,
  artifactStore,
  generatedAt,
  envFile,
  installScript,
}) {
  return {
    schemaVersion: SCHEMA_VERSION,
    generatedAt,
    node: {
      nodeKey: node.nodeKey,
      displayName: node.displayName,
      providerType,
      connectionMode,
      runtimeKind,
      runtimeVersion,
      imageRef,
      status: node.status,
      lifecycleStatus: node.lifecycleStatus,
    },
    stageBindings,
    artifactStore,
    controlPlane: {
      twinStudioUrl,
      heartbeat: {
        method: 'POST',
        url: heartbeatUrl,
        auth: 'bearer-token-from-env',
        tokenEnv: 'TWIN_STUDIO_DATA_FACTORY_TOKEN',
      },
    },
    files: {
      envFile,
      installScript,
    },
    security: {
      tokenReturnedOnce: true,
      tokenStoredIn: envFile,
      note: 'The runtime token is not printed by the CLI. Protect the generated env file as a secret.',
    },
  }
}

function publicNodeFromInput({
  nodeKey,
  displayName,
  providerType,
  connectionMode,
  runtimeKind,
  runtimeVersion,
  imageRef,
}) {
  return {
    nodeKey,
    displayName,
    providerType,
    connectionMode,
    runtimeKind,
    runtimeVersion,
    imageRef,
    status: 'registered',
    lifecycleStatus: 'generated',
  }
}

export async function bootstrapDataFactoryNode(input = {}) {
  const providerType = enumValue(
    input.providerType,
    PROCESSING_NODE_PROVIDER_TYPES,
    'same-server-sidecar',
    'DATA_FACTORY_PROVIDER_TYPE_INVALID',
  )
  const defaultConnectionMode = CONNECTION_MODE_BY_PROVIDER.get(providerType) ?? 'manual'
  const connectionMode = enumValue(
    input.connectionMode,
    PROCESSING_NODE_CONNECTION_MODES,
    defaultConnectionMode,
    'DATA_FACTORY_CONNECTION_MODE_INVALID',
  )
  const runtimeKind = enumValue(
    input.runtimeKind,
    PROCESSING_NODE_RUNTIME_KINDS,
    'docker',
    'DATA_FACTORY_RUNTIME_KIND_INVALID',
  )
  const nodeKey = normalizeKey(input.nodeKey, `${providerType}-${os.hostname()}`)
  const displayName = String(input.displayName ?? '').trim() || `Data Factory ${nodeKey}`
  const runtimeVersion = String(input.runtimeVersion ?? '').trim() || 'local-bootstrap'
  const imageRef = String(input.imageRef ?? '').trim() || 'twin-base-studio-datafactory:local'
  const twinStudioUrl = (String(input.twinStudioUrl ?? '').trim() || 'http://127.0.0.1:3000').replace(/\/+$/g, '')
  const heartbeatUrl = `${twinStudioUrl}/api/data-factory/processing-nodes/${encodeURIComponent(nodeKey)}/heartbeat`
  const stageBindings = splitList(input.stageBindings ?? [], DEFAULT_STAGE_BINDINGS)
    .map((stageKey) => ({ stageKey: normalizeKey(stageKey), enabled: true, priority: 100 }))
  const artifactStore = {
    storeKey: normalizeKey(input.artifactStoreKey, `${nodeKey}-artifact-store`),
    displayName: String(input.artifactStoreName ?? '').trim() || `${displayName} Artifact Store`,
    storeType: String(input.artifactStoreType ?? '').trim() || 'local-filesystem',
    uri: String(input.artifactStoreUri ?? '').trim() || `file:///app/exports/${nodeKey}`,
    publicConfig: {
      root: String(input.artifactRoot ?? '').trim() || `/app/exports/${nodeKey}`,
    },
  }
  const outputDir = path.resolve(String(input.outputDir ?? '').trim() || path.join('runtime-data', 'data-factory-bootstrap', nodeKey))
  const generatedAt = new Date().toISOString()
  const shouldRegister = input.register !== false
  let runtimeToken = String(input.runtimeToken ?? '').trim()
  let node = publicNodeFromInput({
    nodeKey,
    displayName,
    providerType,
    connectionMode,
    runtimeKind,
    runtimeVersion,
    imageRef,
  })

  if (shouldRegister) {
    const registered = await registerProcessingNode({
      nodeKey,
      displayName,
      providerType,
      connectionMode,
      runtimeKind,
      runtimeVersion,
      imageRef,
      status: 'registered',
      lifecycleStatus: 'generated',
      capabilities: {
        bootstrap: SCHEMA_VERSION,
        providerType,
        connectionMode,
        runtimeKind,
      },
      publicConfig: {
        twinStudioUrl,
        heartbeatUrl,
      },
      artifactStore,
      stageBindings,
      issueRuntimeToken: true,
      tokenName: 'bootstrap-runtime-token',
      registeredBy: input.registeredBy ?? 'data-factory-bootstrap-cli',
    })
    if (!registered.ok) throw new Error(registered.error || 'DATA_FACTORY_NODE_REGISTER_FAILED')
    node = registered.node
    runtimeToken = registered.runtimeToken
  }

  if (!runtimeToken) {
    runtimeToken = requireText(input.runtimeToken, 'DATA_FACTORY_RUNTIME_TOKEN_REQUIRED_WHEN_NOT_REGISTERING')
  }

  const envFile = path.join(outputDir, '.env.datafactory.node')
  const installScript = path.join(outputDir, 'install-datafactory-node.sh')
  const bootstrapFile = path.join(outputDir, 'bootstrap.json')
  const commandFile = path.join(outputDir, 'commands.txt')

  writeFile(envFile, buildEnvFile({
    nodeKey,
    providerType,
    connectionMode,
    runtimeKind,
    twinStudioUrl,
    runtimeToken,
    heartbeatUrl,
    projectName: `twin-datafactory-${nodeKey}`,
    imageRef,
    postgisContainer: `twin-datafactory-postgis-${nodeKey}`,
    postgisBind: String(input.postgisBind ?? '').trim() || '127.0.0.1:55432',
    smokeCityId: String(input.smokeCityId ?? '').trim() || 'guanajuato',
  }), 0o600)
  writeFile(installScript, buildInstallScript({ nodeKey, heartbeatUrl }), 0o700)
  writeFile(bootstrapFile, `${JSON.stringify(buildBootstrapJson({
    node,
    providerType,
    connectionMode,
    runtimeKind,
    runtimeVersion,
    imageRef,
    twinStudioUrl,
    heartbeatUrl,
    stageBindings,
    artifactStore,
    generatedAt,
    envFile: path.basename(envFile),
    installScript: path.basename(installScript),
  }), null, 2)}\n`)
  writeFile(commandFile, [
    `ops/datafactory/create-bundle.sh ${shellQuote(path.join(outputDir, 'twin-base-studio-datafactory-bundle.tgz'))}`,
    `bash ${shellQuote(installScript)} ${shellQuote(String(input.installRoot ?? '').trim() || `./twin-base-studio-datafactory-${nodeKey}`)}`,
  ].join('\n') + '\n')

  return {
    ok: true,
    schemaVersion: SCHEMA_VERSION,
    nodeKey,
    providerType,
    connectionMode,
    runtimeKind,
    outputDir,
    bootstrapFile,
    envFile,
    installScript,
    commandFile,
    heartbeatUrl,
    stageBindingCount: stageBindings.length,
    tokenStoredIn: envFile,
    tokenPrinted: false,
    registered: shouldRegister,
  }
}

function cliUsage() {
  return [
    'Usage:',
    '  npm run ops:bootstrap-data-factory-node -- --node-key=<key> [options]',
    '',
    'Options:',
    '  --provider-type=same-server-sidecar|server-to-server-pull|offline-bundle|hpc-batch|cloud-batch',
    '  --connection-mode=local|pull|push|offline|batch|cloud|manual',
    '  --runtime-kind=docker|docker-compose|podman|apptainer|singularity|slurm|pbs|cloud-provider|manual|unknown',
    '  --twin-studio-url=http://127.0.0.1:3000',
    '  --stage=<stage-key>             Repeat or comma-separate. Defaults to current supported Data Factory stages.',
    '  --out=<directory>               Output bootstrap package directory.',
    '  --no-register                   Generate files without DB registration; requires --runtime-token.',
    '  --runtime-token=<token>          Only for --no-register/testing; prefer TWIN_STUDIO_DATA_FACTORY_TOKEN env.',
  ].join('\n')
}

function inputFromCli(argv = process.argv.slice(2)) {
  const providerType = argValue('provider-type', argv) || argValue('providerType', argv) || 'same-server-sidecar'
  const stageBindings = [
    ...argValues('stage', argv),
    ...argValues('stage-key', argv),
    ...argValues('stageKey', argv),
  ]
  return {
    nodeKey: argValue('node-key', argv) || argValue('nodeKey', argv),
    displayName: argValue('display-name', argv) || argValue('displayName', argv),
    providerType,
    connectionMode: argValue('connection-mode', argv) || argValue('connectionMode', argv),
    runtimeKind: argValue('runtime-kind', argv) || argValue('runtimeKind', argv),
    runtimeVersion: argValue('runtime-version', argv) || argValue('runtimeVersion', argv),
    imageRef: argValue('image-ref', argv) || argValue('imageRef', argv),
    twinStudioUrl: argValue('twin-studio-url', argv) || argValue('twinStudioUrl', argv) || process.env.TWIN_STUDIO_BASE_URL,
    artifactStoreKey: argValue('artifact-store-key', argv) || argValue('artifactStoreKey', argv),
    artifactStoreName: argValue('artifact-store-name', argv) || argValue('artifactStoreName', argv),
    artifactStoreType: argValue('artifact-store-type', argv) || argValue('artifactStoreType', argv),
    artifactStoreUri: argValue('artifact-store-uri', argv) || argValue('artifactStoreUri', argv),
    artifactRoot: argValue('artifact-root', argv) || argValue('artifactRoot', argv),
    outputDir: argValue('out', argv) || argValue('output', argv) || argValue('output-dir', argv),
    installRoot: argValue('install-root', argv) || argValue('installRoot', argv),
    postgisBind: argValue('postgis-bind', argv) || argValue('postgisBind', argv),
    smokeCityId: argValue('city', argv) || argValue('smoke-city', argv) || argValue('smokeCity', argv),
    stageBindings,
    register: !booleanArg('no-register', argv),
    runtimeToken: argValue('runtime-token', argv) || argValue('runtimeToken', argv) || process.env.TWIN_STUDIO_DATA_FACTORY_TOKEN,
    registeredBy: argValue('registered-by', argv) || argValue('registeredBy', argv),
  }
}

async function main() {
  const argv = process.argv.slice(2)
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(cliUsage())
    return
  }

  const input = inputFromCli(argv)
  if (input.register && !productionDatabaseConfigured()) {
    console.log(JSON.stringify({
      ok: true,
      skipped: true,
      reason: 'DATABASE_URL_NOT_CONFIGURED',
      hint: 'Use --no-register --runtime-token=<token> to generate a local package without touching PostGIS.',
    }, null, 2))
    return
  }

  try {
    if (input.register) await runProductionMigrations()
    const result = await bootstrapDataFactoryNode(input)
    console.log(JSON.stringify(result, null, 2))
  } finally {
    await closeProductionPool()
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(JSON.stringify({
      ok: false,
      error: String(error?.message ?? 'DATA_FACTORY_NODE_BOOTSTRAP_FAILED'),
    }, null, 2))
    process.exit(1)
  })
}
